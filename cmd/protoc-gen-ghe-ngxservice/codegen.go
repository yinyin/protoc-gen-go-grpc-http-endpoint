package main

import (
	"strings"

	nameconv "github.com/yinyin/go-convert-naming-convention"
	"google.golang.org/protobuf/compiler/protogen"

	protocgenghe "github.com/yinyin/protoc-gen-go-grpc-http-endpoint"
)

type codeGenParameters struct {
	outputFilePath string
	fieldOptions   protocgenghe.NgxFieldNameOptions
}

func (param *codeGenParameters) Normalize(generatedFilenamePrefix string) (result *codeGenParameters) {
	result = &codeGenParameters{
		outputFilePath: generatedFilenamePrefix + "_ghe.service.ts",
	}
	if param == nil {
		return
	}
	if param.outputFilePath != "" {
		result.outputFilePath = param.outputFilePath
	}
	result.fieldOptions = param.fieldOptions
	return
}

func buildURLPathCodes(urlPath *protocgenghe.URLPath) (urlPathCode string, hndParamCodes []string) {
	urlPathCodeParts := make([]string, 0, len(urlPath.Parts))
	templateMode := false
	for _, urlPart := range urlPath.Parts {
		switch urlPart.PartType {
		case protocgenghe.URLPathPartFixed:
			urlPathCodeParts = append(urlPathCodeParts, protocgenghe.EscapeTypescriptString(string(urlPart.FixedPath)))
		case protocgenghe.URLPathPartCapture:
			templateMode = true
			if urlPart.DestFieldName != "" {
				urlPathCodeParts = append(urlPathCodeParts, "${req."+urlPart.DestFieldName+"}")
			} else if urlPart.DestSetterFuncName != "" {
				urlPathCodeParts = append(urlPathCodeParts, "/* TODO(not-implement-yet): ${req."+urlPart.DestSetterFuncName+"()} */")
			} else if urlPart.DestHandlerParamName != "" {
				tsParamType := protocgenghe.GoTypeToTypescriptType(urlPart.DestHandlerParamType)
				urlPathCodeParts = append(urlPathCodeParts, "${"+urlPart.DestHandlerParamName+"}")
				hndParamCodes = append(hndParamCodes, (urlPart.DestHandlerParamName + ": " + tsParamType))
			} else {
				// unknown capture type
				urlPathCodeParts = append(urlPathCodeParts, "/* TODO(unknown-capture-type): "+urlPart.CaptureName+" */")
			}
		}
	}
	if templateMode {
		urlPathCode = "`/" + strings.Join(urlPathCodeParts, "") + "`"
	} else {
		urlPathCode = "\"/" + strings.Join(urlPathCodeParts, "") + "\""
	}
	return
}

func genNgxServiceCode(
	dbgFp *protocgenghe.GeneratedDebugFile,
	gen *protogen.Plugin,
	param *codeGenParameters,
	destInfo *protocgenghe.OneCodeGenDestInfo,
	endpointPaths *protocgenghe.EndpointPathContainer) error {
	param = param.Normalize(destInfo.GeneratedFilenamePrefix)
	rg := gen.NewGeneratedFile(param.outputFilePath, destInfo.GoImportPath)
	rg.P("// Code generated by protoc-gen-ghe-ngxservice. DO NOT EDIT.")
	rg.P("// versions:")
	rg.P("// - protoc-gen-ghe-ngxservice v", protocgenghe.CodeVersion)
	rg.P("// - protoc                    ", protocgenghe.ProtocVersion(gen))
	rg.P("// sources (", len(destInfo.SourceProtoFilePaths), "):")
	for _, protoFilePath := range destInfo.SourceProtoFilePaths {
		rg.P("// - ", protoFilePath)
	}
	rg.P()
	rg.P("import { HttpClient } from '@angular/common/http';")
	rg.P("import { Injectable } from '@angular/core';")
	rg.P("import { Observable } from 'rxjs';")
	rg.P()
	payloadMessages := protocgenghe.CollectMethodPayloadMessages(
		dbgFp,
		endpointPaths.SortedEndpointServices(),
		destInfo.MergedNgxNamingConvOpts,
		&param.fieldOptions)
	messageGenerated := make(map[string]struct{})
	for _, msgRef := range payloadMessages.Sorted() {
		rg.P("// ", msgRef.FullName)
		if (msgRef.DescRef.Desc.FullName().Parent() == "google.protobuf") ||
			(msgRef.DescRef.Desc.IsMapEntry()) {
			rg.P()
			continue
		}
		messageGenerated[msgRef.FullName] = struct{}{}
		leadComments := msgRef.DescRef.Comments.Leading.String()
		if leadComments != "" {
			rg.P(leadComments)
		}
		rg.P("export interface ", msgRef.NgxName, " {")
		for _, fieldRef := range msgRef.PayloadFields {
			typeAnnoToken := ": "
			typeAnnoSuffix := ";"
			if !fieldRef.NgxAlwaysDefined {
				typeAnnoToken = "?: "
			}
			if fieldRef.NgxNullable {
				typeAnnoSuffix = " | null;"
			}
			// typeFullName := "?"
			// if fieldRef.MessageRef != nil {
			// 	typeFullName = fieldRef.MessageRef.FullName
			// }
			rg.P("  ", fieldRef.NgxName, typeAnnoToken, fieldRef.NgxTypeName, typeAnnoSuffix)
		}
		rg.P("}")
		rg.P()
	}
	for _, serviceRef := range endpointPaths.SortedEndpointServices() {
		serviceClassName := nameconv.ToUpperCamelCase(
			string(serviceRef.DescRef.Desc.Name()),
			serviceRef.NgxNamingConvOpts) + "Service"
		rg.P("@Injectable({providedIn: 'root'})")
		rg.P("export class ", serviceClassName, " {")
		rg.P("  constructor(private http: HttpClient) { }")
		for _, methodRef := range serviceRef.Methods {
			rg.P()
			methodName := nameconv.ToLowerCamelCase(methodRef.RouteIdentSuffix, serviceRef.NgxNamingConvOpts)
			if methodRef.DescRef == nil {
				rg.P("  // ", methodRef.RouteIdentTail, " (not RPC method)")
				continue
			}
			inputMessage := payloadMessages.Find(methodRef.DescRef.Input)
			outputMessage := payloadMessages.Find(methodRef.DescRef.Output)
			var methodParamList string
			var haveRequestBody bool
			if _, ok := messageGenerated[inputMessage.FullName]; ok {
				methodParamList = "req: " + inputMessage.NgxName
				haveRequestBody = true
			}
			outputMessageType := outputMessage.NgxName
			var urlPathCode string
			var needRequestBody bool
			var hndParamCodes []string
			var httpRequestCode string
			if methodRef.EndpointPostURLPath != nil {
				urlPathCode, hndParamCodes = buildURLPathCodes(methodRef.EndpointPostURLPath)
				httpRequestCode = "this.http.post<" + outputMessageType + ">(" + urlPathCode + ", req)"
				needRequestBody = true
			} else if methodRef.EndpointGetURLPath != nil {
				urlPathCode, hndParamCodes = buildURLPathCodes(methodRef.EndpointGetURLPath)
				httpRequestCode = "this.http.get<" + outputMessageType + ">(" + urlPathCode + ")"
			} else if methodRef.EndpointPutURLPath != nil {
				urlPathCode, hndParamCodes = buildURLPathCodes(methodRef.EndpointPutURLPath)
				httpRequestCode = "this.http.put<" + outputMessageType + ">(" + urlPathCode + ", req)"
				needRequestBody = true
			} else if methodRef.EndpointDeleteURLPath != nil {
				urlPathCode, hndParamCodes = buildURLPathCodes(methodRef.EndpointDeleteURLPath)
				httpRequestCode = "this.http.delete<" + outputMessageType + ">(" + urlPathCode + ")"
			} else if methodRef.EndpointPatchURLPath != nil {
				urlPathCode, hndParamCodes = buildURLPathCodes(methodRef.EndpointPatchURLPath)
				httpRequestCode = "this.http.patch<" + outputMessageType + ">(" + urlPathCode + ", req)"
				needRequestBody = true
			} else if methodRef.EndpointHeadURLPath != nil {
				urlPathCode, hndParamCodes = buildURLPathCodes(methodRef.EndpointHeadURLPath)
				httpRequestCode = "this.http.head<" + outputMessageType + ">(" + urlPathCode + ")"
			} else if methodRef.EndpointOptionsURLPath != nil {
				urlPathCode, hndParamCodes = buildURLPathCodes(methodRef.EndpointOptionsURLPath)
				httpRequestCode = "this.http.options<" + outputMessageType + ">(" + urlPathCode + ")"
			} else {
				httpRequestCode = "/* TODO(not-implement-yet): unknown HTTP method */"
			}
			if len(hndParamCodes) > 0 {
				if methodParamList != "" {
					methodParamList += ", "
				}
				methodParamList += strings.Join(hndParamCodes, ", ")
			}
			rg.P("  ", methodName, "(", methodParamList, "): Observable<", outputMessageType, "> {")
			if needRequestBody && !haveRequestBody {
				rg.P("    const req = {};")
			}
			rg.P("    return ", httpRequestCode, ";")
			rg.P("}")
		}
		rg.P("}")
		rg.P()
	}
	return nil
}
